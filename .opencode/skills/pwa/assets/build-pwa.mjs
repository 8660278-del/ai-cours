import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

async function exportedFiles(directory, prefix = "") {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = `${prefix}${entry.name}`;
    if (
      relative === "api" ||
      entry.name.startsWith(".") ||
      relative === "sw.js" ||
      relative.endsWith(".map")
    )
      continue;
    if (entry.isDirectory()) {
      files.push(
        ...(await exportedFiles(
          path.join(directory, entry.name),
          `${relative}/`
        ))
      );
    } else if (entry.isFile()) {
      files.push(relative);
    }
  }
  return files.sort();
}

export async function buildPwa({
  projectDir = process.cwd(),
  staticExport = false,
} = {}) {
  const root = path.join(projectDir, staticExport ? "out" : "public");
  const files = staticExport ? await exportedFiles(root) : ["offline.html"];
  if (!files.includes("offline.html"))
    throw new Error("PWA build requires offline.html");
  const encodePath = (file) =>
    file.split("/").map(encodeURIComponent).join("/");
  const routes = Object.create(null);
  for (const file of files.filter((file) => file.endsWith(".html"))) {
    const encoded = encodePath(file);
    routes[encoded] = encoded;
    if (file === "index.html" || file.endsWith("/index.html")) {
      const directory = encoded.slice(0, -"index.html".length);
      routes[directory] = encoded;
      if (directory) routes[directory.slice(0, -1)] = encoded;
    } else {
      const route = encoded.slice(0, -".html".length);
      routes[route] = encoded;
      routes[`${route}/`] = encoded;
    }
  }
  const worker = await readFile(
    new URL("./pwa-worker.js", import.meta.url),
    "utf8"
  );
  const mode = staticExport ? "static" : "server";
  const hash = createHash("sha256")
    .update(JSON.stringify({ mode, routes }))
    .update(worker);
  for (const file of files) {
    hash
      .update(file)
      .update("\0")
      .update(
        createHash("sha256")
          .update(await readFile(path.join(root, file)))
          .digest()
      );
  }
  const version = hash.digest("hex").slice(0, 20);
  const source = `/* Generated by scripts/build-pwa.mjs. Do not edit. */\nconst PWA_MODE = ${JSON.stringify(mode)};\nconst BUILD_VERSION = ${JSON.stringify(version)};\nconst PRECACHE_PATHS = ${JSON.stringify(files.map(encodePath))};\nconst NAVIGATION_ROUTES = ${JSON.stringify(routes)};\n\n${worker}`;
  await mkdir(path.join(projectDir, "public"), { recursive: true });
  await writeFile(path.join(projectDir, "public/sw.js"), source);
  if (staticExport) await writeFile(path.join(root, "sw.js"), source);
  console.log(`PWA: ${mode}, ${files.length} resources, revision ${version}`);
}

if (
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url
) {
  await buildPwa({
    staticExport:
      process.argv.includes("--static") || process.env.OUTPUT_MODE === "export",
  });
}
