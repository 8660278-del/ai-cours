function createLesson(
  moduleNumber: number,
  lessonNumber: number,
  seed: LessonSeed,
  minutes: number
): CourseLesson {
  const numberLabel = `${moduleNumber}.${lessonNumber}`;
  const id = `lesson-${moduleNumber}-${lessonNumber}`;

  const blocks: LessonBlock[] = seed.blocks ?? [
    {
      id: `${id}-intro`,
      type: "text",
      title: "Введение",
      paragraphs: [
        seed.goal,
        "Материал урока разбит на последовательные блоки. Прочитайте их по порядку и выполните практическое задание — только после этого урок будет отмечен пройденным.",
      ],
    },
    {
      id: `${id}-goal`,
      type: "card",
      title: "Цель урока",
      body: seed.goal,
      tone: "accent",
    },
    {
      id: `${id}-topics`,
      type: "list",
      title: "Что разберём",
      items: seed.topics,
    },
    {
      id: `${id}-practice`,
      type: "task",
      taskId: `${id}-task`,
      title: "Практическое задание",
      description:
        "Примените материал урока к рабочей ситуации из вашей практики: сформулируйте запрос к ИИ и проверьте полученный результат.",
      instructions: [
        "Прочитайте все блоки урока по порядку.",
        "Выберите рабочую ситуацию, к которой применим материал урока.",
        "Подготовьте запрос и проверьте результат по критериям ниже.",
        "Подтвердите выполнение задания — после этого урок будет отмечен пройденным.",
      ],
      criteria: [
        "Запрос содержит задачу, контекст и ожидаемый формат результата.",
        "Результат проверен на факты, расчёты и отсутствие запрещённых данных.",
        "Понятно, какие правки нужно внести перед использованием результата.",
      ],
    },
    {
      id: `${id}-memo`,
      type: "memo",
      title: "Ключевые выводы",
      items: [
        `Тема урока: ${seed.title.toLowerCase()}.`,
        "ИИ ускоряет подготовку, но итоговую проверку выполняет человек.",
        "Возвращайтесь к памятке модуля при выполнении рабочих задач.",
      ],
    },
  ];

  return {
    id,
    numberLabel,
    title: seed.title,
    duration: `${minutes} мин`,
    goal: seed.goal,
    blocks,
  };
}

