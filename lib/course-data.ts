export const courseModules: CourseModule[] = moduleSeeds.map((seed, index) => {
  const minutes = Math.round((seed.hours * 60) / seed.lessons.length);

  return {
    id: seed.id,
    order: index + 1,
    title: seed.title,
    duration: seed.duration,
    goal: seed.goal,
    intro: seed.intro,
    outcomes: seed.outcomes,
    content: seed.content,
    summary: seed.summary,
    memo: seed.memo,
    lessons: seed.lessons.map((lesson, lessonIndex) =>
      createLesson(index + 1, lessonIndex + 1, lesson, minutes)
    ),
  };
});

export const totalLessons = courseModules.reduce(
  (sum, module) => sum + module.lessons.length,
  0
);

export function getModuleById(moduleId: string): CourseModule | undefined {
  return courseModules.find((module) => module.id === moduleId);
}

export function getLessonById(
  moduleId: string,
  lessonId: string
): CourseLesson | undefined {
  return getModuleById(moduleId)?.lessons.find(
    (lesson) => lesson.id === lessonId
  );
}

export function getModuleByLessonId(
  lessonId: string
): CourseModule | undefined {
  return courseModules.find((module) =>
    module.lessons.some((lesson) => lesson.id === lessonId)
  );
}
