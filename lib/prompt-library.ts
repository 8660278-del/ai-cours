export function getPromptCategory(
  categoryId: string
): PromptCategory | undefined {
  return promptCategories.find((category) => category.id === categoryId);
}

export function findPromptCategoryId(value: string): string | undefined {
  const normalized = value.trim().toLowerCase();

  return promptCategories.find(
    (category) =>
      category.id === normalized || category.title.toLowerCase() === normalized
  )?.id;
}
