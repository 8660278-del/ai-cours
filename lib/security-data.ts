export function getSecurityVerdictOption(verdict: SecurityVerdict) {
  return securityVerdicts.find((option) => option.id === verdict);
}

export function scoreSecurityTrainer(
  answers: Record<string, SecurityVerdict>
): { correct: number; total: number } {
  let correct = 0;

  for (const situation of securityTrainerSituations) {
    if (answers[situation.id] === situation.correct) {
      correct += 1;
    }
  }

  return { correct, total: securityTrainerSituations.length };
}

export function getSecuritySituation(id: string) {
  return securityTrainerSituations.find((situation) => situation.id === id);
}
