export type SecurityVerdict = "allowed" | "conditional" | "forbidden";

export type SecurityLevelTone =
  | "open"
  | "internal"
  | "confidential"
  | "restricted";

export interface SecurityLevel {
  id: string;
  title: string;
  badge: string;
  tone: SecurityLevelTone;
  summary: string;
  examples: string[];
  rules: string[];
}

export interface ProtocolStep {
  id: string;
  title: string;
  body: string;
}

export interface SecuritySituation {
  id: string;
  title: string;
  scenario: string;
  details: string[];
  correct: SecurityVerdict;
  explanation: string;
  conditions?: string;
}

export interface SecurityVerdictOption {
  id: SecurityVerdict;
  label: string;
  short: string;
}

export interface SecurityTrainerResult {
  answers: Record<string, SecurityVerdict>;
  correct: number;
  total: number;
  completedAt: string;
}

